/**
 * Generates docs/section-schemas.md from the Zod schemas registered in
 * src/components/sections/schemas-registry.ts.
 *
 * The output is the single human-readable reference for what content keys
 * each section (and variant) accepts. Builders authoring site.config.ts
 * and pipeline emitters should read this instead of opening every
 * src/components/sections/*\/index.tsx by hand.
 *
 * Run via `pnpm gen:schemas`. Also runnable from CI to verify the doc
 * stays in sync with the schemas (commit any diff).
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import { z } from "zod";
import { SECTION_SCHEMAS } from "../src/components/sections/schemas-registry";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, "..");
const outPath = path.join(repoRoot, "docs/section-schemas.md");

interface KeyInfo {
  name: string;
  required: boolean;
}

function getShape(schema: z.ZodTypeAny): Record<string, z.ZodTypeAny> | null {
  // ZodObject exposes `.shape` (Zod 4). Non-objects return null.
  const obj = schema as unknown as { shape?: Record<string, z.ZodTypeAny> };
  if (obj && typeof obj.shape === "object" && obj.shape !== null) return obj.shape;
  return null;
}

function describeKeys(schema: z.ZodTypeAny): KeyInfo[] {
  const shape = getShape(schema);
  if (!shape) return [];
  return Object.entries(shape).map(([name, def]) => ({
    name,
    required: !(def as unknown as { isOptional: () => boolean }).isOptional(),
  }));
}

function bullets(keys: KeyInfo[]): string {
  if (keys.length === 0) return "_(none)_";
  return keys
    .map((k) => (k.required ? `\`${k.name}\` (required)` : `\`${k.name}\``))
    .join(", ");
}

function namesOnly(keys: string[]): string {
  if (keys.length === 0) return "—";
  return keys.map((k) => `\`${k}\``).join(", ");
}

function render(): string {
  const lines: string[] = [];
  lines.push("# Section Content Schemas");
  lines.push("");
  lines.push(
    "Auto-generated from the Zod schemas co-located with each section component (`src/components/sections/<Section>/schema.ts`) via the central registry at `src/components/sections/schemas-registry.ts`. Do not edit this file directly — update the section's `schema.ts` and run `pnpm gen:schemas`."
  );
  lines.push("");
  lines.push(
    "This is the contract between `site.config.ts` and the section renderer. Every `section.content` object is validated against the entry below at prebuild time (`pnpm prebuild` → `section-shape-scanner`). Unknown keys are flagged as typos; missing required keys fail the build."
  );
  lines.push("");
  lines.push(`Total registered section types: **${Object.keys(SECTION_SCHEMAS).length}**.`);
  lines.push("");
  lines.push("---");
  lines.push("");

  const types = Object.keys(SECTION_SCHEMAS).sort();
  for (const type of types) {
    const entry = SECTION_SCHEMAS[type];
    const baseKeys = describeKeys(entry.base);
    lines.push(`## \`${type}\``);
    lines.push("");
    lines.push(`- **Base keys:** ${bullets(baseKeys)}`);

    if (entry.variants && Object.keys(entry.variants).length > 0) {
      lines.push("");
      lines.push("### Variants");
      lines.push("");
      lines.push("| Variant | Adds required | Adds optional |");
      lines.push("| --- | --- | --- |");
      const baseByName = new Map(baseKeys.map((k) => [k.name, k]));
      for (const variant of Object.keys(entry.variants).sort()) {
        const vKeys = describeKeys(entry.variants[variant]);
        const addedRequired: string[] = [];
        const addedOptional: string[] = [];
        for (const k of vKeys) {
          const baseK = baseByName.get(k.name);
          if (!baseK) {
            (k.required ? addedRequired : addedOptional).push(k.name);
            continue;
          }
          // Key existed in base; flag only if its required-ness was tightened
          if (k.required && !baseK.required) addedRequired.push(k.name);
        }
        lines.push(
          `| \`${variant}\` | ${namesOnly(addedRequired)} | ${namesOnly(addedOptional)} |`
        );
      }
    }
    lines.push("");
  }
  return lines.join("\n");
}

function main() {
  const out = render();
  fs.mkdirSync(path.dirname(outPath), { recursive: true });
  fs.writeFileSync(outPath, out, "utf-8");
  console.log(`gen-section-schemas: wrote ${path.relative(repoRoot, outPath)}`);
}

main();
